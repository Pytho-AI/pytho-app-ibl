#!/usr/bin/env bash
#
# Pytho macOS / Linux local run script
# Gets Docker, Elasticsearch, env files, and compose (API + UI) running for local testing.
#
# Usage:
#   ELASTIC_PASSWORD=yourpassword ./scripts/install-mac.sh
#   or
#   ./scripts/install-mac.sh yourpassword
#
# Optional:
#   PYTHO_DATA=/path/to/data ./scripts/install-mac.sh   # default: ./data (relative to project root)
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PYTHO_DATA="${PYTHO_DATA:-$PROJECT_ROOT/data}"
QA_MODEL="${QA_MODEL:-gemma3:4b-it-qat}"
AUDIO_MODEL="${AUDIO_MODEL:-medium.en}"

# ELASTIC_PASSWORD: from first arg or env
if [[ -n "${1:-}" ]]; then
  ELASTIC_PASSWORD="$1"
elif [[ -z "${ELASTIC_PASSWORD:-}" ]]; then
  echo "Usage: ELASTIC_PASSWORD=yourpassword $0"
  echo "   or: $0 yourpassword"
  exit 1
fi

echo "========================================"
echo "   Pytho local run (macOS/Linux)       "
echo "========================================"
echo ""
echo "Project root: $PROJECT_ROOT"
echo "Data directory: $PYTHO_DATA"
echo ""

# --- 1. Docker check ---
echo "[1/7] Checking Docker..."
if ! command -v docker &>/dev/null; then
  echo "  Docker is not installed or not in PATH. Install Docker Desktop (Mac) or docker (Linux) and try again."
  exit 1
fi
if ! docker info &>/dev/null; then
  echo "  Docker daemon is not running. Start Docker Desktop or run: sudo systemctl start docker (Linux)."
  exit 1
fi
echo "  Docker is available and running."

# --- 2. Data directories ---
echo "[2/7] Setting up data directories..."
mkdir -p "$PYTHO_DATA"/{models,data,uploads,resources,sd-models/Stable-diffusion,sd-outputs,es-data}
# ES container runs as uid 1000; on Mac/Linux chown may need sudo
if [[ "$(uname)" = "Darwin" ]] || [[ -w "$PYTHO_DATA" ]]; then
  chmod -R 755 "$PYTHO_DATA"
  if command -v id &>/dev/null && [[ "$(id -u)" -eq 0 ]]; then
    chown -R 1000:1000 "$PYTHO_DATA/es-data" 2>/dev/null || true
  fi
fi
echo "  Data directories ready at $PYTHO_DATA"

# --- 3. Start Elasticsearch ---
echo "[3/7] Starting Elasticsearch..."
cd "$PROJECT_ROOT"
export ELASTIC_PASSWORD PYTHO_DATA
docker compose -f docker-compose-edge.yml up -d es-secure

# --- Wait for ES healthy ---
echo "  Waiting for Elasticsearch to be ready..."
max_retries=30
retry_interval=5
for (( i=1; i<=max_retries; i++ )); do
  if curl -sf -u "elastic:${ELASTIC_PASSWORD}" "http://localhost:9200/_cluster/health" >/dev/null 2>&1; then
    status=$(curl -sf -u "elastic:${ELASTIC_PASSWORD}" "http://localhost:9200/_cluster/health" | grep -o '"status":"[^"]*"' | cut -d'"' -f4)
    if [[ "$status" == "green" || "$status" == "yellow" ]]; then
      echo "  Elasticsearch is ready (status: $status)"
      break
    fi
  fi
  if [[ $i -eq max_retries ]]; then
    echo "  Elasticsearch did not become ready in time. Check: docker compose -f docker-compose-edge.yml logs es-secure"
    exit 1
  fi
  echo "  Not ready yet (attempt $i/$max_retries)..."
  sleep "$retry_interval"
done

# --- 4. Create ES API key ---
echo "[4/7] Creating Elasticsearch API key..."
api_key_body='{
  "name": "doc-chunks-service-'$(date +%Y%m%d-%H%M%S)'",
  "role_descriptors": {
    "doc_chunks_rw": {
      "cluster": ["monitor"],
      "indices": [{
        "names": ["doc_chunks", "doctrine_chunks"],
        "privileges": ["read", "write", "delete", "create_index", "view_index_metadata"]
      }]
    }
  }
}'
auth=$(echo -n "elastic:${ELASTIC_PASSWORD}" | base64)
resp=$(curl -sf -X POST "http://localhost:9200/_security/api_key" \
  -H "Authorization: Basic $auth" \
  -H "Content-Type: application/json" \
  -d "$api_key_body") || {
  echo "  Failed to create API key. Is Elasticsearch running and ELASTIC_PASSWORD correct?"
  exit 1
}
ES_ACCESS_ID=$(echo "$resp" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('id',''))")
ES_ACCESS_KEY=$(echo "$resp" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('api_key',''))")
if [[ -z "$ES_ACCESS_ID" || -z "$ES_ACCESS_KEY" ]]; then
  echo "  Failed to parse API key from response."
  exit 1
fi
echo "  API key created (id: $ES_ACCESS_ID)"

# --- 5. Generate app/.env ---
echo "[5/7] Configuring environment..."
app_env="$PROJECT_ROOT/app/.env"
cat > "$app_env" << EOF
# Pytho Environment Configuration
# Generated by install-mac.sh on $(date "+%Y-%m-%d %H:%M:%S")

# Service Configuration
SERVICE_HOST=host.docker.internal
UPLOAD_DIR=uploads
FILE_HOST_API=http://localhost:8000/files/

# Elasticsearch Configuration
ES_HOST=es-secure
ES_ACCESS_ID=$ES_ACCESS_ID
ES_ACCESS_KEY=$ES_ACCESS_KEY

# AI Models
Q_AND_A_MODEL=$QA_MODEL
AUDIO_MODEL=$AUDIO_MODEL

# Stable Diffusion (for Facebook post images; use container name when in Docker)
IMAGE_API_HOST=stability_api
IMAGE_API_PORT=17860

# Optional: Slack Integration (update with your token)
# SLACK_TOKEN=xoxb-your-token-here

# Optional: Gemini API (update with your key)
# GEMINI_API_KEY=your-key-here
EOF
echo "  Wrote $app_env"

# --- 6. Create ui/.env (so compose does not fail) ---
echo "[6/7] Creating ui/.env..."
ui_env="$PROJECT_ROOT/ui/.env"
touch "$ui_env"
echo "# Optional env for nginx (left empty for local testing)" > "$ui_env"
echo "  Wrote $ui_env"

# --- Copy default resources if empty ---
if [[ -d "$PROJECT_ROOT/resources" ]] && [[ -z "$(ls -A "$PYTHO_DATA/resources" 2>/dev/null)" ]]; then
  echo "  Copying default templates to data directory..."
  cp -R "$PROJECT_ROOT/resources"/* "$PYTHO_DATA/resources/" 2>/dev/null || true
fi

# --- 7. Deploy app + UI ---
echo "[7/7] Building and starting API and UI..."
docker compose -f docker-compose-edge.yml up -d --build --force-recreate docker-api nginx
echo "  API and UI started."

# Optional: start Kokoro TTS if not running
if ! docker ps --format '{{.Names}}' 2>/dev/null | grep -q 'kokoro_tts'; then
  echo "  Starting Kokoro TTS..."
  docker compose -f docker-compose-edge.yml up -d kokoro-tts 2>/dev/null || true
fi

# Optional: start Stable Diffusion (CPU) if not running
if ! docker ps --format '{{.Names}}' 2>/dev/null | grep -q 'stability_api'; then
  echo "  Starting Stable Diffusion (CPU)..."
  docker compose -f docker-compose-edge.yml --profile cpu up -d stability-api-cpu 2>/dev/null || true
fi

echo ""
echo "========================================"
echo "   Local run complete                  "
echo "========================================"
echo ""
echo "  UI:  http://localhost:8080"
echo "  API: http://localhost:8000"
echo ""
echo "  To view logs: docker compose -f docker-compose-edge.yml logs -f"
echo "  To stop:      docker compose -f docker-compose-edge.yml down"
echo ""
